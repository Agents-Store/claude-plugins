#!/bin/sh
# Все тесты плагина, одной командой.
#
# Прогон существует потому, что тестов было два и НИГДЕ не было сказано, что они
# есть. Проверка, которую никто не запускает, ничем не отличается от её
# отсутствия — и оба дефекта, найденные 2026-08-27, прожили ровно столько,
# сколько прожило это молчание.
#
# Файлы ищутся, а не перечисляются: список пришлось бы дописывать, а забытый
# файл выглядел бы как «тестов больше нет», то есть как успех.
#
# Три вещи здесь сделаны нарочно, и каждая — по разу уже сломавшись:
#   /bin/sh без bashism — `mapfile` есть только в bash 4+, а macOS поставляет 3.2;
#   чтение путей построчно, а не `for f in $(find …)` — путь к плагину содержит
#     пробел, и подстановка разбивала его на два несуществующих файла;
#   счётчик падений через файл-метку — `while` в конвейере идёт в подоболочке,
#     и присвоенная там переменная наружу не возвращается: прогон рапортовал бы
#     успех при упавших тестах.
set -u
ROOT=$(cd "$(dirname "$0")" && pwd)
LIST=$(mktemp)
MARK=$(mktemp)
trap 'rm -f "$LIST" "$MARK"' EXIT
# Ищутся и тесты скиллов, и тесты плагина как целого: сверка манифеста с
# записью в каталоге маркетплейса ничьим скиллом не является. `-maxdepth`
# нет намеренно — глубина каталогов у скиллов разная.
find "$ROOT/skills" "$ROOT/tests" -name 'test_*.py' 2>/dev/null | sort > "$LIST"

FOUND=$(wc -l < "$LIST" | tr -d ' ')
if [ "$FOUND" -eq 0 ]; then
    echo "тестов не найдено под $ROOT/skills — это ошибка, а не пустой прогон" >&2
    exit 1
fi

while IFS= read -r f; do
    printf '\n=== %s\n' "$(basename "$f")"
    # Каждый файл запускается из своего каталога: они кладут в sys.path соседние
    # модули относительно себя.
    ( cd "$(dirname "$(dirname "$f")")" && python3 -W ignore "$f" ) || echo x >> "$MARK"
done < "$LIST"

printf '\n'
if [ -s "$MARK" ]; then
    echo "ЕСТЬ ПАДЕНИЯ — см. выше" >&2
    exit 1
fi
echo "все тесты плагина прошли ($FOUND файла)"
